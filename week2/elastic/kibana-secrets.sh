#!/bin/bash
# Kibana secrets in a root-owned config file instead of environment variables.
# Why: the Kibana image turns env vars into command-line flags, and any local user can read
# command lines with `ps`. Run ON core-arm in ~/soc-lab/week2/elastic:
#   ./kibana-secrets.sh render    fresh deploy: write kibana.secrets.yml from .env (before `docker compose up`)
#   ./kibana-secrets.sh rotate    new kibana_system password + 3 new Kibana keys, saved objects re-encrypted
#   ./kibana-secrets.sh finish    after rotate: drop the old key, restart, prove everything still decrypts
#   ./kibana-secrets.sh keep-old  if finish found a problem: put the old key back (decryption only)
#   ./kibana-secrets.sh cleanup   once all is fine: delete the backup holding the old (leaked) values
#   ./kibana-secrets.sh rollback  restore the .env backup left by a failed rotate, and apply it
# Prints no secrets. Credentials go to curl through a private temp file, never on a command line.
set -euo pipefail
cd "$(dirname "$0")"
umask 077
[ -f .env ] || { echo "no .env - run gen-env.sh first"; exit 1; }
set -a; . ./.env; set +a
CA=/etc/elastic-agent-certs/ca.crt
ES="https://${BIND_IP}:9200"; KB="https://${BIND_IP}:5601"
OUT=kibana.secrets.yml
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
printf 'machine %s login elastic password %s\n' "$BIND_IP" "$ELASTIC_PASSWORD" > "$TMP/netrc"
c() { curl -sS --cacert "$CA" --netrc-file "$TMP/netrc" -H 'Content-Type: application/json' -H 'kbn-xsrf: true' "$@"; }
IMG=$(docker compose config --images | grep -m1 '/kibana/kibana')

render() {   # $1 = old saved-objects key to keep for decryption only (optional)
  docker run --rm --entrypoint cat "$IMG" /usr/share/kibana/config/kibana.yml \
    | grep -vE '^\s*(#|$)|^elasticsearch\.(hosts|password)|encryptionKey|keyRotation' > "$TMP/base" || true
  { echo "# Generated by kibana-secrets.sh from .env - DO NOT COMMIT"
    cat "$TMP/base"
    echo "elasticsearch.password: \"${KIBANA_PASSWORD}\""
    echo "xpack.security.encryptionKey: \"${KIBANA_SECURITY_KEY}\""
    echo "xpack.reporting.encryptionKey: \"${KIBANA_REPORTING_KEY}\""
    echo "xpack.encryptedSavedObjects.encryptionKey: \"${KIBANA_SAVEDOBJECTS_KEY}\""
    if [ -n "${1:-}" ]; then echo "xpack.encryptedSavedObjects.keyRotation.decryptionOnlyKeys: [\"$1\"]"; fi
  } > "$TMP/new"
  local gid=20998   # dedicated group given to the Kibana container (group_add); unused on the host
  # write in place (same inode), so a running container's bind mount sees the new content
  [ -f "$OUT" ] || sudo install -o root -g "$gid" -m 0640 /dev/null "$OUT"
  sudo chown "root:$gid" "$OUT"; sudo chmod 0640 "$OUT"
  sudo tee "$OUT" >/dev/null < "$TMP/new"
  echo "   $OUT written: $(sudo grep -c . "$OUT") lines, owner $(stat -c '%U:%g %a' "$OUT")$( [ -n "${1:-}" ] && echo ', old key kept for decryption only')"
}
set_kibana_system_pw() {
  jq -n --arg p "$KIBANA_PASSWORD" '{password: $p}' > "$TMP/pw.json"
  [ "$(c -X POST "$ES/_security/user/kibana_system/_password" -d @"$TMP/pw.json")" = "{}" ] \
    && echo "   kibana_system password set in Elasticsearch" || { echo "   FAILED to set kibana_system password"; exit 1; }
}
wait_kibana() {
  printf '   waiting for Kibana'
  for _ in $(seq 1 60); do
    [ "$(c "$KB/api/status" 2>/dev/null | jq -r '.status.overall.level // empty' 2>/dev/null)" = available ] && { echo " - available"; return 0; }
    printf '.'; sleep 5
  done
  echo " - NOT available after 5 min"; docker compose logs --tail 15 kibana | cut -c1-200; return 1
}
leak_check() {
  local n; n=$(ps -eo args | grep -E -- '--elasticsearch\.password|encryptionKey' | grep -vc grep || true)
  echo "   secrets visible in process list: $n $( [ "$n" -eq 0 ] && echo OK || echo CHECK)"
}

case "${1:-}" in
render)
  render; echo "RENDER DONE" ;;
rotate)
  grep -q 'kibana.secrets.yml' docker-compose.yml || { echo "STOP: docker-compose.yml is the old version - copy the new one first"; exit 1; }
  echo "== 1/5 new secrets in .env (backup kept until success)"
  cp -p .env ".env.bak-rotate"
  OLD_ESO="$KIBANA_SAVEDOBJECTS_KEY"
  sed -i -e "s/^KIBANA_PASSWORD=.*/KIBANA_PASSWORD=$(openssl rand -hex 20)/" \
         -e "s/^KIBANA_SECURITY_KEY=.*/KIBANA_SECURITY_KEY=$(openssl rand -hex 32)/" \
         -e "s/^KIBANA_SAVEDOBJECTS_KEY=.*/KIBANA_SAVEDOBJECTS_KEY=$(openssl rand -hex 32)/" \
         -e "s/^KIBANA_REPORTING_KEY=.*/KIBANA_REPORTING_KEY=$(openssl rand -hex 32)/" .env
  set -a; . ./.env; set +a
  echo "   4 values replaced; ELASTIC_PASSWORD unchanged"
  echo "== 2/5 config file (new keys + old saved-objects key for decryption only)"
  render "$OLD_ESO"
  echo "== 3/5 new kibana_system password, Kibana recreated without secrets in its environment"
  set_kibana_system_pw
  docker compose up -d --no-deps kibana 2>&1 | tail -2
  wait_kibana || { echo "STOPPED - run: ./kibana-secrets.sh rollback"; exit 1; }
  echo "== 4/5 re-encrypt saved objects (Fleet, rules) with the new key"
  R=$(c -X POST "$KB/api/encrypted_saved_objects/_rotate_key")
  echo "   $(echo "$R" | jq -c '{total, successful, failed}')"
  [ "$(echo "$R" | jq -r '.failed')" = 0 ] || { echo "STOPPED - some objects not re-encrypted; old key kept, Kibana still works. Paste this."; exit 1; }
  echo "== 5/5 drop the old key, restart, verify"
  render
  docker compose restart kibana >/dev/null 2>&1
  wait_kibana || exit 1
  leak_check
  echo "   Fleet agents online: $(c "$KB/api/fleet/agents?perPage=20" | jq '[.items[] | select(.status=="online")] | length')"
  echo "   detection rules enabled: $(c "$KB/api/detection_engine/rules/_find?per_page=50" | jq '[.data[] | select(.enabled)] | length')"
  echo "ROTATE DONE - log in to Kibana again (old sessions are invalid now)" ;;
finish)
  grep -q '20998' docker-compose.yml || { echo "STOP: docker-compose.yml is the old version - copy the new one first"; exit 1; }
  [ -f .env.bak-rotate ] || { echo "no .env.bak-rotate - was rotate run?"; exit 1; }
  echo "== 1/3 config without the old key; Kibana recreated with its own file group"
  render
  docker compose up -d --no-deps kibana 2>&1 | tail -1
  docker compose restart kibana >/dev/null 2>&1
  SINCE=$(date -u +%Y-%m-%dT%H:%M:%SZ)
  wait_kibana || { echo "STOPPED - run: ./kibana-secrets.sh keep-old"; exit 1; }
  echo "   Kibana runs with groups: $(docker compose exec -T kibana id -G)"
  leak_check
  echo "== 2/3 can Kibana decrypt everything with the new key alone?"
  echo "   Fleet setup: $(c -X POST "$KB/api/fleet/setup" | jq -c '{isInitialized, nonFatalErrors: (.nonFatalErrors|length)}')"
  for id in $(c "$KB/api/fleet/uninstall_tokens?perPage=20" | jq -r '.items[].id'); do
    ok=$(c "$KB/api/fleet/uninstall_tokens/$id" | jq -r 'if (.item.token // "" | length) > 0 then "readable" else "NOT READABLE" end')
    echo "   uninstall token ${id:0:8}...: $ok"
  done
  echo "   waiting 6 min so every rule runs at least once with the new key only..."; sleep 360
  c "$KB/api/detection_engine/rules/_find?per_page=50" | jq -r --arg s "$SINCE" '.data[] | "   \(if (.execution_summary.last_execution.date // "") > $s then "ran" else "NOT RUN YET" end)  \(.execution_summary.last_execution.status // "-")  \(.name)"'
  E=$(docker compose logs kibana --since "$SINCE" 2>&1 | grep -ciE 'unable to decrypt|failed to decrypt|decryption failed' || true)
  echo "   decryption errors in Kibana log since restart: $E $( [ "$E" -eq 0 ] && echo OK || echo CHECK)"
  echo "== 3/3 agents online: $(c "$KB/api/fleet/agents?perPage=20" | jq '[.items[] | select(.status=="online")] | length')"
  echo "FINISH DONE - if all OK: ./kibana-secrets.sh cleanup ; if any CHECK: ./kibana-secrets.sh keep-old" ;;
keep-old)
  [ -f .env.bak-rotate ] || { echo "no .env.bak-rotate - old key not available"; exit 1; }
  OLD_ESO=$(grep '^KIBANA_SAVEDOBJECTS_KEY=' .env.bak-rotate | cut -d= -f2)
  render "$OLD_ESO"; docker compose restart kibana >/dev/null 2>&1; wait_kibana
  echo "KEEP-OLD DONE (old key back for decryption only; paste the finish output)" ;;
cleanup)
  [ -f .env.bak-rotate ] && { shred -u .env.bak-rotate 2>/dev/null || rm -f .env.bak-rotate; echo "   backup with old values deleted"; } || echo "   no backup present"
  echo "CLEANUP DONE" ;;
rollback)
  [ -f .env.bak-rotate ] || { echo "no .env.bak-rotate - nothing to roll back"; exit 1; }
  cp -p .env.bak-rotate .env; set -a; . ./.env; set +a
  render; set_kibana_system_pw
  docker compose up -d --no-deps kibana 2>&1 | tail -2; docker compose restart kibana >/dev/null 2>&1
  wait_kibana; leak_check; echo "ROLLBACK DONE (old secrets back - rotate again once fixed)" ;;
*) echo "usage: $0 render|rotate|rollback"; exit 1 ;;
esac
